export type MessageKey = keyof typeof messages

export function t(key: MessageKey, params?: Array<string | number>): string {
  const template: string = messages[key] ?? key
  if (!params || params.length === 0) return template
  return params.reduce<string>(
    (text, value, index) => text.replace(`{${index}}`, String(value)),
    template
  )
}

